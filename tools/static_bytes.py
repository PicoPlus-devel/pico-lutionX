#!/usr/bin/env python3
"""Sum the static data (.data/.bss, i.e. what lives in RAM) of object files.

Usage: static_bytes.py [--header] <nm> <object>...
Prints the total in bytes, or with --header a C header defining DX_ENGINE_STATIC_BYTES.
Sanitizer bookkeeping symbols are not counted.
"""
import subprocess
import sys

args = sys.argv[1:]
header = False
if args and args[0] == '--header':
    header = True
    args = args[1:]
nm, objects = args[0], args[1:]
total = 0
for start in range(0, len(objects), 200):
    out = subprocess.run([nm, '-S', '-t', 'd'] + objects[start:start + 200],
                         capture_output=True, text=True).stdout
    for line in out.splitlines():
        parts = line.split()
        if len(parts) != 4 or parts[2] not in 'bBdDcC':
            continue
        name = parts[3]
        if 'asan' in name or 'ubsan' in name or name.startswith('__'):
            continue
        total += int(parts[1])
if header:
    print('// Generated by tools/static_bytes.py: static data of the engine objects.')
    print('#pragma once')
    print(f'#define DX_ENGINE_STATIC_BYTES {total}u')
else:
    print(total)
